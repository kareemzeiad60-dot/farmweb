#!/usr/bin/env node
// Generates the domain-table migrations from src/data/db-schema.js.
//   node scripts/generate-sql.js
// Writes:
//   supabase/migrations/002_domain_tables.sql
//   supabase/migrations/003_migrate_legacy_records.sql
const fs = require("fs");
const path = require("path");
const { databaseSchema, databaseTableOrder, databaseColumnName } = require("../src/data/db-schema.js");

const root = path.join(__dirname, "..");
const outDir = path.join(root, "supabase", "migrations");
const sqlTypes = { text: "text", numeric: "numeric", int: "integer", date: "date", bool: "boolean", uuid: "uuid" };

const tableOf = (resourceId) => databaseSchema[resourceId].table;
const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

function columnDefinition(column) {
  const name = databaseColumnName(column);
  const parts = [name, sqlTypes[column.type]];
  if (column.type === "bool") {
    parts.push("not null", `default ${column.default ? "true" : "false"}`);
  } else if (column.type === "text") {
    parts.push(column.required ? "not null" : "not null default ''");
  } else if (column.required) {
    parts.push("not null");
  }
  return parts.join(" ");
}

function tableSql(resourceId) {
  const spec = databaseSchema[resourceId];
  const t = spec.table;
  const textId = spec.idType === "text";
  const lines = [];
  lines.push(textId ? "id text not null" : "id uuid primary key default gen_random_uuid()");
  lines.push("farm_id uuid not null references public.farms (id) on delete cascade");
  lines.push("created_by uuid default auth.uid() references auth.users (id) on delete set null");
  for (const column of spec.columns) lines.push(columnDefinition(column));
  lines.push("extra jsonb not null default '{}'::jsonb check (jsonb_typeof(extra) = 'object')");
  lines.push("created_at timestamptz not null default now()");
  lines.push("updated_at timestamptz not null default now()");
  lines.push(textId
    ? `constraint ${t}_pkey primary key (farm_id, id)`
    : `constraint ${t}_farm_id_id_key unique (farm_id, id)`);
  for (const column of spec.columns) {
    const name = databaseColumnName(column);
    if (column.min !== undefined) lines.push(`constraint ${t}_${name}_min check (${name} >= ${column.min})`);
    if (column.ref && !column.noFk) {
      lines.push(`constraint ${t}_${name}_fkey foreign key (farm_id, ${name}) references public.${tableOf(column.ref)} (farm_id, id) on delete set null (${name})`);
    }
  }
  if (spec.rangeCheck) {
    const [from, to] = spec.rangeCheck.map((field) => databaseColumnName({ field }));
    lines.push(`constraint ${t}_date_range check (${to} >= ${from})`);
  }

  const out = [];
  out.push(`-- ${resourceId}`);
  out.push(`create table if not exists public.${t} (\n  ${lines.join(",\n  ")}\n);`);
  out.push(`create index if not exists ${t}_farm_created_idx on public.${t} (farm_id, created_at desc);`);
  for (const column of spec.columns.filter((c) => c.ref && !c.noFk)) {
    const name = databaseColumnName(column);
    out.push(`create index if not exists ${t}_${name}_idx on public.${t} (farm_id, ${name});`);
  }
  out.push(`drop trigger if exists set_updated_at on public.${t};`);
  out.push(`create trigger set_updated_at before update on public.${t}\n  for each row execute function public.set_updated_at();`);
  out.push(`alter table public.${t} enable row level security;`);
  out.push(`revoke all on public.${t} from anon, public;`);
  out.push(`grant select, insert, update, delete on public.${t} to authenticated;`);
  out.push(`drop policy if exists "Farm members can view ${t}" on public.${t};`);
  out.push(`create policy "Farm members can view ${t}"\n  on public.${t} for select to authenticated\n  using (public.is_farm_member(farm_id));`);
  out.push(`drop policy if exists "Farm editors can insert ${t}" on public.${t};`);
  out.push(`create policy "Farm editors can insert ${t}"\n  on public.${t} for insert to authenticated\n  with check (public.can_write_farm(farm_id));`);
  out.push(`drop policy if exists "Farm editors can update ${t}" on public.${t};`);
  out.push(`create policy "Farm editors can update ${t}"\n  on public.${t} for update to authenticated\n  using (public.can_write_farm(farm_id))\n  with check (public.can_write_farm(farm_id));`);
  out.push(`drop policy if exists "Farm editors can delete ${t}" on public.${t};`);
  out.push(`create policy "Farm editors can delete ${t}"\n  on public.${t} for delete to authenticated\n  using (public.can_write_farm(farm_id));`);
  return out.join("\n");
}

const header002 = `-- 002 - Domain tables (generated by scripts/generate-sql.js - do not edit by hand).
-- One real table per Fieldwise resource, replacing the generic farm_records.data jsonb store.
-- Requires 001_core.sql first. Needs PostgreSQL 15+ (ON DELETE SET NULL (column)), which all
-- current Supabase projects provide.
--
-- Every row carries farm_id; composite foreign keys (farm_id, ref_id) make cross-farm links
-- impossible. Keys the app does not map to a column are kept in the \`extra\` jsonb column.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Owners, managers and workers may change farm data; viewers are read-only.
create or replace function public.can_write_farm(p_farm_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.farm_members m
    where m.farm_id = p_farm_id
      and m.user_id = (select auth.uid())
      and m.role in ('owner', 'manager', 'worker')
  );
$$;

revoke all on function public.can_write_farm(uuid) from public, anon;
grant execute on function public.can_write_farm(uuid) to authenticated;
`;

const sql002 = `${header002}\n${databaseTableOrder.map(tableSql).join("\n\n")}\n`;

// ---------------------------------------------------------------- 003 legacy data copy
function legacyColumnExpr(column) {
  const key = quote(column.field);
  const raw = `r.data ->> ${key}`;
  if (column.field === "relatedRecord") {
    return `coalesce(nullif(r.related_record_id, ''), ${raw}, '')`;
  }
  switch (column.type) {
    case "text": return `coalesce(${raw}, '')`;
    case "numeric": return `public.fw_try_numeric(${raw})`;
    case "int": return `public.fw_try_int(${raw})`;
    case "date": return `public.fw_try_date(${raw})`;
    case "bool": return `public.fw_try_bool(${raw}, ${column.default ? "true" : "false"})`;
    case "uuid":
      if (column.noFk) return `public.fw_try_uuid(${raw})`;
      return `(select x.id from public.${tableOf(column.ref)} x where x.farm_id = r.farm_id and x.id = public.fw_try_uuid(${raw}))`;
    default: throw new Error(`Unknown type ${column.type}`);
  }
}

function legacyGuards(spec) {
  const guards = [];
  for (const column of spec.columns) {
    const expr = legacyColumnExpr(column);
    if (column.required && column.type !== "text") guards.push(`${expr} is not null`);
    if (column.min !== undefined) guards.push(`(${expr} is null or ${expr} >= ${column.min})`);
  }
  if (spec.rangeCheck) {
    const [from, to] = spec.rangeCheck.map((field) => spec.columns.find((c) => c.field === field));
    guards.push(`${legacyColumnExpr(to)} >= ${legacyColumnExpr(from)}`);
  }
  return guards;
}

function legacySql(resourceId) {
  const spec = databaseSchema[resourceId];
  const textId = spec.idType === "text";
  const names = ["id", "farm_id", "created_by", ...spec.columns.map(databaseColumnName), "extra", "created_at", "updated_at"];
  const knownKeys = ["id", "createdAt", "updatedAt", ...spec.columns.map((c) => c.field)];
  const values = [
    textId ? "r.record_id" : "public.fw_try_uuid(r.record_id)",
    "r.farm_id",
    "r.user_id",
    ...spec.columns.map(legacyColumnExpr),
    `coalesce(r.data, '{}'::jsonb) - array[${knownKeys.map(quote).join(", ")}]::text[]`,
    "r.created_at",
    "r.updated_at",
  ];
  const where = [`r.record_type = ${quote(resourceId)}`];
  if (!textId) where.push("public.fw_try_uuid(r.record_id) is not null");
  where.push(...legacyGuards(spec));
  return `-- ${resourceId}
insert into public.${spec.table} (${names.join(", ")})
select ${values.join(",\n       ")}
from public.farm_records r
where ${where.join("\n  and ")}
on conflict (farm_id, id) do nothing;`;
}

const header003 = `-- 003 - Copy existing rows from the legacy farm_records table into the domain tables
-- (generated by scripts/generate-sql.js - do not edit by hand).
-- Safe to run more than once. Rows that already exist are left alone, and farm_records itself is
-- NOT modified or dropped, so you can verify first. The last query compares row counts per type;
-- if legacy_rows and new_rows differ, inspect those rows before dropping farm_records.
-- Rows are skipped when their id is not a UUID (non-holiday records), when a required number or
-- date is missing, or when a value would break a CHECK constraint.

create or replace function public.fw_try_numeric(v text) returns numeric language plpgsql immutable as $$
begin return nullif(btrim(v), '')::numeric; exception when others then return null; end; $$;
create or replace function public.fw_try_int(v text) returns integer language plpgsql immutable as $$
begin return round(nullif(btrim(v), '')::numeric)::integer; exception when others then return null; end; $$;
create or replace function public.fw_try_date(v text) returns date language plpgsql immutable as $$
begin return nullif(btrim(v), '')::date; exception when others then return null; end; $$;
create or replace function public.fw_try_uuid(v text) returns uuid language plpgsql immutable as $$
begin return nullif(btrim(v), '')::uuid; exception when others then return null; end; $$;
create or replace function public.fw_try_bool(v text, fallback boolean) returns boolean language sql immutable as $$
  select case lower(btrim(coalesce(v, '')))
    when 'true' then true when 't' then true
    when 'false' then false when 'f' then false
    else fallback end;
$$;
`;

const report = `-- Verification: legacy rows vs migrated rows
select * from (
${databaseTableOrder.map((id) => `  select ${quote(id)} as record_type,
         (select count(*) from public.farm_records where record_type = ${quote(id)}) as legacy_rows,
         (select count(*) from public.${tableOf(id)}) as new_rows`).join("\n  union all\n")}
) counts
order by record_type;

drop function public.fw_try_bool(text, boolean);
drop function public.fw_try_uuid(text);
drop function public.fw_try_date(text);
drop function public.fw_try_int(text);
drop function public.fw_try_numeric(text);
`;

const sql003 = `${header003}\n${databaseTableOrder.map(legacySql).join("\n\n")}\n\n${report}`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "002_domain_tables.sql"), sql002);
fs.writeFileSync(path.join(outDir, "003_migrate_legacy_records.sql"), sql003);
console.log("Wrote 002_domain_tables.sql and 003_migrate_legacy_records.sql");
